"""Replaces the old make-perl.c + generate.pl.in two-stage generator.

Invocation mirrors the old `perl -p generate.pl SRCDIR TEMPLATE`:

    python3 generate.py SRCDIR TEMPLATE > OUTPUT

TEMPLATE is read line by line; any line containing one of the
LIBSPECTRUM_* markers below is replaced by generated content, everything
else is passed through unchanged. Feature flags (stdint.h, GLib, gcrypt,
zlib, bz2, WAV backend) are read directly out of the build's config.h,
which autoconf already fills in with the resolved HAVE_* defines - no
compiled C probe is needed for that part.

The one case the old C probe handled that config.h can't is the pre-C99
"no stdint.h" fallback, which picked typedefs from sizeof(short) etc.
measured by the build-time compiler. That path is only relevant to
compilers that predate stdint.h (e.g. the old MSVC6 special case in the
previous implementation); it's effectively dead on every toolchain this
project currently targets, so this version approximates it using
ctypes' view of C type sizes rather than invoking a compiler, and drops
the MSVC6-specific __int64 branch.
"""

import ctypes
import re
import sys


def read_config_flags(path="config.h"):
    flags = set()
    try:
        with open(path) as f:
            for line in f:
                m = re.match(r'\s*#\s*define\s+(HAVE_\w+)\b', line)
                if m:
                    flags.add(m.group(1))
    except FileNotFoundError:
        pass
    return flags


def autogen_warning():
    return (
        "/* NB: This file is autogenerated from libspectrum.h.in. Do not edit\n"
        "   unless you know what you're doing */\n"
    )


def define_types(flags):
    if "HAVE_STDINT_H" in flags:
        return (
            "#include <stdint.h>\n"
            "\n"
            "typedef  uint8_t libspectrum_byte;\n"
            "typedef   int8_t libspectrum_signed_byte;\n"
            "typedef uint16_t libspectrum_word;\n"
            "typedef  int16_t libspectrum_signed_word;\n"
            "typedef uint32_t libspectrum_dword;\n"
            "typedef  int32_t libspectrum_signed_dword;\n"
            "typedef uint64_t libspectrum_qword;\n"
            "typedef  int64_t libspectrum_signed_qword;\n"
        )

    out = []

    if ctypes.sizeof(ctypes.c_char) == 1:
        out.append("typedef unsigned char libspectrum_byte;\n")
        out.append("typedef   signed char libspectrum_signed_byte;\n")
    elif ctypes.sizeof(ctypes.c_short) == 1:
        out.append("typedef unsigned short libspectrum_byte;\n")
        out.append("typedef   signed short libspectrum_signed_byte;\n")
    else:
        sys.exit("No plausible 8 bit types found")

    if ctypes.sizeof(ctypes.c_short) == 2:
        out.append("typedef unsigned short libspectrum_word;\n")
        out.append("typedef   signed short libspectrum_signed_word;\n")
    elif ctypes.sizeof(ctypes.c_int) == 2:
        out.append("typedef unsigned int libspectrum_word;\n")
        out.append("typedef   signed int libspectrum_signed_word;\n")
    else:
        sys.exit("No plausible 16 bit types found")

    if ctypes.sizeof(ctypes.c_int) == 4:
        out.append("typedef unsigned int libspectrum_dword;\n")
        out.append("typedef   signed int libspectrum_signed_dword;\n")
    elif ctypes.sizeof(ctypes.c_long) == 4:
        out.append("typedef unsigned long libspectrum_dword;\n")
        out.append("typedef   signed long libspectrum_signed_dword;\n")
    else:
        sys.exit("No plausible 32 bit types found")

    if ctypes.sizeof(ctypes.c_long) == 8:
        out.append("typedef unsigned long libspectrum_qword;\n")
        out.append("typedef   signed long libspectrum_signed_qword;\n")
    elif ctypes.sizeof(ctypes.c_longlong) == 8:
        out.append("typedef unsigned long long libspectrum_qword;\n")
        out.append("typedef   signed long long libspectrum_signed_qword;\n")
    else:
        sys.exit("No plausible 64 bit types found")

    return "".join(out)


