TRAILER = (
    "\n"
    "    default:\n"
    "      libspectrum_print_error(\n"
    "        LIBSPECTRUM_ERROR_INVALID,\n"
    '        "invalid block type 0x%2x given to %s", block->type, __func__\n'
    "      );\n"
    "      return LIBSPECTRUM_ERROR_INVALID;\n"
    "  }\n"
    "\n"
    "  libspectrum_tape_block_changed( block );\n"
    "  return LIBSPECTRUM_ERROR_NONE;\n"
    "}\n"
    "\n"
)


def _perl_truthy(value):
    """Mirror Perl boolean context: '' and '0' (and None) are false."""
    return value is not None and value != "" and value != "0"


def parse_and_emit(lines, out):
    name = None
    indexed = None
    pointer = None
    started = False

    for raw_line in lines:
        line = re.sub(r'#.*', '', raw_line)

        if re.match(r'^\s*$', line):
            continue

        if re.match(r'^\s', line):
            # Which block types this accessor applies to.
            fields = line.split()
            member_type = fields[0] if len(fields) > 0 else None
            member = fields[1] if len(fields) > 1 else None
            if not _perl_truthy(member):
                member = name

            out.append(
                "    case LIBSPECTRUM_TAPE_BLOCK_%s: block->types.%s.%s = %s%s; break;\n"
                % (
                    member_type.upper(),
                    member_type,
                    member,
                    '*' if _perl_truthy(pointer) else '',
                    name,
                )
            )

        else:
            if started:
                out.append(TRAILER)

            fields = line.split()
            c_type = fields[0] if len(fields) > 0 else None
            name = fields[1] if len(fields) > 1 else None
            indexed = fields[2] if len(fields) > 2 else None
            # fields[3] (default) isn't used by the 'set' side.
            pointer = fields[4] if len(fields) > 4 else None

            out.append(
                "libspectrum_error\nlibspectrum_tape_block_set_%s( libspectrum_tape_block *block, %s %s%s"
                % (name, c_type, '*' if _perl_truthy(indexed) else '', name)
            )
            out.append(" )\n{\n  switch( block->type ) {\n\n")

            started = True

    if started:
        out.append(TRAILER)


def main(argv):
    if len(argv) < 2:
        sys.exit("usage: %s TAPE_ACCESSORS_TXT" % argv[0])

    # Avoid platform newline translation (e.g. \n -> \r\n on native Windows
    # Python) so output is identical regardless of host OS.
    sys.stdout.reconfigure(newline='')

    out = [HEADER % (argv[1], os.path.basename(argv[0]))]

    with open(argv[1]) as f:
        parse_and_emit(f, out)

    sys.stdout.write("".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
