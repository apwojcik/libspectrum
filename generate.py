def glib_replacement(flags):
    if "HAVE_LIB_GLIB" in flags:
        return "#define LIBSPECTRUM_HAS_GLIB_REPLACEMENT 0\n"

    out = _GLIB_REPLACEMENT_DECLS

    void_p = ctypes.sizeof(ctypes.c_void_p)
    if void_p == ctypes.sizeof(ctypes.c_int):
        out += (
            "#define GINT_TO_POINTER(i)      ((gpointer)  (i))\n"
            "#define GPOINTER_TO_INT(p)      ((gint)   (p))\n"
            "#define GPOINTER_TO_UINT(p)     ((guint)  (p))\n"
        )
    elif void_p == ctypes.sizeof(ctypes.c_long):
        out += (
            "#define GINT_TO_POINTER(i)      ((gpointer)  (glong)(i))\n"
            "#define GPOINTER_TO_INT(p)      ((gint)   (glong)(p))\n"
            "#define GPOINTER_TO_UINT(p)     ((guint)  (gulong)(p))\n"
        )
    elif void_p == ctypes.sizeof(ctypes.c_longlong):
        out += (
            "#define GINT_TO_POINTER(i)      ((gpointer)  (long long)(i))\n"
            "#define GPOINTER_TO_INT(p)      ((gint)   (long long)(p))\n"
            "#define GPOINTER_TO_UINT(p)     ((guint)  (unsigned long long)(p))\n"
        )
    else:
        sys.exit("No plausible int to pointer cast found")

    return out


def include_gcrypt(flags):
    if "HAVE_GCRYPT_H" in flags:
        return "#include <gcrypt.h>\n"
    return ""


def signature_parameters(flags):
    if "HAVE_GCRYPT_H" in flags:
        return "  /* The DSA signature parameters 'r' and 's' */\n  gcry_mpi_t r, s;\n"
    return "/* Signature parameters not stored as libgcrypt is not present */\n"


def capabilities(flags):
    out = []

    if "HAVE_ZLIB_H" in flags:
        out.append(
            "\n/* we support snapshots etc. requiring zlib (e.g. compressed szx) */\n"
            "#define\tLIBSPECTRUM_SUPPORTS_ZLIB_COMPRESSION\t(1)\n"
            "\n"
            "/* zlib (de)compression routines */\n"
            "\n"
            "LIBSPECTRUM_API libspectrum_error\n"
            "libspectrum_zlib_inflate( const libspectrum_byte *gzptr, size_t gzlength,\n"
            "\t\t\t  libspectrum_byte **outptr, size_t *outlength );\n"
            "\n"
            "LIBSPECTRUM_API libspectrum_error\n"
            "libspectrum_zlib_compress( const libspectrum_byte *data, size_t length,\n"
            "\t\t\t   libspectrum_byte **gzptr, size_t *gzlength );\n"
            "\n"
        )

    if "HAVE_LIBBZ2" in flags:
        out.append(
            "\n/* we support files compressed with bz2 */\n"
            "#define\tLIBSPECTRUM_SUPPORTS_BZ2_COMPRESSION\t(1)\n"
            "\n"
        )

    if "HAVE_WAV_BACKEND" in flags:
        out.append(
            "\n/* we support wav files */\n"
            "/* LIBSPECTRUM_SUPPORTS_AUDIOFILE is deprecated; use "
            "LIBSPECTRUM_SUPPORTS_WAV instead. */\n"
            "#define\tLIBSPECTRUM_SUPPORTS_AUDIOFILE\t(1)\n"
            "#define\tLIBSPECTRUM_SUPPORTS_WAV\t(1)\n"
            "\n"
        )

    return "".join(out)


def _perl_truthy(value):
    """Mirror Perl boolean context: '' and '0' (and undef) are false."""
    return value is not None and value != "" and value != "0"


def _return_type(c_type):
    m = re.match(r'^(.*)\*', c_type)
    if m:
        return "LIBSPECTRUM_API %s *" % m.group(1)
    return "LIBSPECTRUM_API %s" % c_type


def snap_accessors(srcdir):
    out = []
    with open("%s/snap_accessors.txt" % srcdir) as f:
        for line in f:
            if re.match(r'^\s*$', line):
                continue
            if re.match(r'^\s*#', line):
                continue
            if re.match(r'^\s*/\*', line):
                continue
            line = re.sub(r'/\*(.*)\*/', '', line)

            fields = line.split()
            c_type = fields[0] if len(fields) > 0 else None
            name = fields[1] if len(fields) > 1 else None
            indexed = fields[2] if len(fields) > 2 else None

            return_type = _return_type(c_type)

            if _perl_truthy(indexed):
                out.append(
                    "%s libspectrum_snap_%s( libspectrum_snap *snap, int idx );\n"
                    "LIBSPECTRUM_API void libspectrum_snap_set_%s( libspectrum_snap *snap, int idx, %s %s );\n"
                    % (return_type, name, name, c_type, name)
                )
            else:
                out.append(
                    "%s libspectrum_snap_%s( libspectrum_snap *snap );\n"
                    "LIBSPECTRUM_API void libspectrum_snap_set_%s( libspectrum_snap *snap, %s %s );\n"
                    % (return_type, name, name, c_type, name)
                )
    return "".join(out)


def tape_accessors(srcdir):
    out = []
    with open("%s/tape_accessors.txt" % srcdir) as f:
        for line in f:
            line = re.sub(r'#.*', '', line)
            if re.match(r'^\s*$', line):
                continue
            # Skip which block types each accessor applies to
            if re.match(r'^\s', line):
                continue

            fields = line.split()
            c_type = fields[0] if len(fields) > 0 else None
            name = fields[1] if len(fields) > 1 else None
            indexed = fields[2] if len(fields) > 2 else None

            return_type = _return_type(c_type)

            if _perl_truthy(indexed):
                out.append(
                    "%s libspectrum_tape_block_%s( libspectrum_tape_block *block, size_t idx );\n"
                    "LIBSPECTRUM_API libspectrum_error libspectrum_tape_block_set_%s( libspectrum_tape_block *block, %s *%s );\n"
                    % (return_type, name, name, c_type, name)
                )
            else:
                out.append(
                    "%s libspectrum_tape_block_%s( libspectrum_tape_block *block );\n"
                    "LIBSPECTRUM_API libspectrum_error libspectrum_tape_block_set_%s( libspectrum_tape_block *block, %s %s );\n"
                    % (return_type, name, name, c_type, name)
                )
    return "".join(out)


_MARKERS = (
    ("LIBSPECTRUM_AUTOGEN_WARNING", lambda flags, srcdir: autogen_warning()),
    ("LIBSPECTRUM_DEFINE_TYPES", lambda flags, srcdir: define_types(flags)),
    ("LIBSPECTRUM_GLIB_REPLACEMENT", lambda flags, srcdir: glib_replacement(flags)),
    ("LIBSPECTRUM_INCLUDE_GCRYPT", lambda flags, srcdir: include_gcrypt(flags)),
    ("LIBSPECTRUM_SIGNATURE_PARAMETERS", lambda flags, srcdir: signature_parameters(flags)),
    ("LIBSPECTRUM_CAPABILITIES", lambda flags, srcdir: capabilities(flags)),
    ("LIBSPECTRUM_SNAP_ACCESSORS", lambda flags, srcdir: snap_accessors(srcdir)),
    ("LIBSPECTRUM_TAPE_ACCESSORS", lambda flags, srcdir: tape_accessors(srcdir)),
)


def main(argv):
    # Avoid platform newline translation (e.g. \n -> \r\n on native Windows
    # Python) so output is identical regardless of host OS.
    sys.stdout.reconfigure(newline='')

    srcdir = argv[1]
    template_path = argv[2]

    flags = read_config_flags("config.h")

    with open(template_path) as f:
        for line in f:
            replaced = False
            for marker, handler in _MARKERS:
                if marker in line:
                    sys.stdout.write(handler(flags, srcdir))
                    replaced = True
            if not replaced:
                sys.stdout.write(line)

    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
